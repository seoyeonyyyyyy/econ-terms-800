FALLBACK = ("금융상식", "금융시장")

TERM_WEIGHT = 3   # 용어명에 등장한 키워드 가중치

# 키워드를 통째로 품고 있지만 뜻이 전혀 다른 말. 이 안에 든 것은 세지 않는다.
# 한국어는 복합어가 공백 없이 붙어서, 짧은 키워드는 엉뚱한 단어에 걸린다
# (실측: "전월세 전환율"이 '환율' 때문에 외환으로 분류됐다).
DECOYS: dict[str, list[str]] = {
    "환율": ["전환율", "교환율", "변환율"],
    "수입": ["수입산", "수입원"],
    "경기": ["호경기", "불경기"],      # 이미 별도 키워드로 잡으므로 이중계산을 막는다
}

def _count(text: str, kw: str) -> int:
    n = text.count(kw)
    for decoy in DECOYS.get(kw, ()):
        n -= text.count(decoy)
    return max(n, 0)

def _score(term: str, text: str) -> Counter:
    """키워드 길이로 가중한다. 긴 키워드일수록 그 분야에만 쓰이는 말이다."""
    scores = Counter()
    for sub, (_cat, keywords) in SUBCATEGORIES.items():
        s = 0
        for kw in keywords:
            weight = len(kw)
            s += _count(term, kw) * weight * TERM_WEIGHT
            s += _count(text, kw) * weight
        if s:
            scores[sub] = s
    return scores

def classify(term: str, definition: str) -> tuple[str, str]:
    scores = _score(term, definition[:400])
    if not scores:
        return FALLBACK

    top = scores.most_common()
    if len(top) > 1 and top[0][1] == top[1][1]:
        # 동점이면 첫 문장만으로 다시 매긴다
        first = definition.split(".")[0]
        tie = {s for s, v in top if v == top[0][1]}
        refined = _score(term, first)
        narrowed = [(s, v) for s, v in refined.most_common() if s in tie]
        sub = narrowed[0][0] if narrowed else sorted(tie)[0]
    else:
        sub = top[0][0]

    return SUBCATEGORIES[sub][0], sub

def main():
    raw = json.loads(Path("build/raw_terms.json").read_text(encoding="utf-8"))
    for rec in raw:
        cat, sub = classify(rec["term"], rec["def"])
        rec["category"], rec["subcategory"] = cat, sub

    Path("data").mkdir(exist_ok=True)
    Path("data/terms.json").write_text(
        json.dumps(raw, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    by_cat = Counter(r["category"] for r in raw)
    by_sub = Counter(r["subcategory"] for r in raw)
    print(f"분류 완료: {len(raw)}개")
    for cat, n in by_cat.most_common():
        print(f"  {cat:8s} {n:4d}")
    print()
    for sub, n in by_sub.most_common():
        print(f"    {sub:22s} {n:4d}")
    empty = set(SUBCATEGORIES) - set(by_sub)
    if empty:
        print("비어 있는 소분류:", sorted(empty))

if __name__ == "__main__":
    main()
